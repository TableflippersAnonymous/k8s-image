#!/bin/bash
#
# Give the NICs deterministic names and hand systemd-networkd this node's
# addresses.  Runs after initialize-hostname.sh and before systemd-networkd.
#
# The kernel boots with net.ifnames=0, so the NICs arrive as eth0..eth5 in
# whatever order they were probed.  Here they are sorted:
#
#   eth0..eth3  1GbE, by MAC   -> unconfigured, left for diagnostics
#   eth4 eth5   10GbE, by MAC  -> bond private, the node's only data path,
#                                 carrying vlan 14 native + 12 and 17 tagged
#
# Only the two 10GbE ports are required.  The 1GbE ports get stable names
# if they are present, but nothing depends on them.

set -u

GE_DRIVERS="igb igc e1000 e1000e tg3 bnx2"
XE_DRIVERS="ixgbe ixgbevf i40e ice bnx2x mlx4_en mlx5_core"

fatal() {
  echo "initialize-network: $*" >&2
  echo "initialize-network: $*" > /dev/kmsg 2>/dev/null || true
  exit 1
}

inventory() {
  local path dev
  for path in /sys/class/net/*; do
    dev="${path##*/}"
    [[ -e "$path/device" ]] || continue
    echo "  ${dev} mac=$(< "$path/address")" \
         "driver=$(basename "$(readlink -f "$path/device/driver" 2>/dev/null)")" \
         "speed=$(cat "$path/speed" 2>/dev/null || echo unknown)"
  done
}

# --- classify -------------------------------------------------------------

ge=()
xe=()

classify() {
  local path dev mac drv speed
  ge=()
  xe=()
  for path in /sys/class/net/*; do
    dev="${path##*/}"
    [[ -e "$path/device" ]] || continue         # skip lo and virtual devices
    mac="$(< "$path/address")"
    drv="$(basename "$(readlink -f "$path/device/driver" 2>/dev/null)")"

    case " ${GE_DRIVERS} " in
      *" ${drv} "*) ge+=("${mac} ${dev}"); continue ;;
    esac
    case " ${XE_DRIVERS} " in
      *" ${drv} "*) xe+=("${mac} ${dev}"); continue ;;
    esac

    # Unrecognised driver: fall back to link speed, which is only readable
    # once the link is up.  Better than nothing, and the count check below
    # catches it if the link was still down.
    speed="$(cat "$path/speed" 2>/dev/null || echo 0)"
    if [[ "$speed" -ge 10000 ]]; then
      xe+=("${mac} ${dev}")
    elif [[ "$speed" -ge 1000 ]]; then
      ge+=("${mac} ${dev}")
    fi
  done
  [[ "${#xe[@]}" -eq 2 && "${#ge[@]}" -le 4 ]]
}

# PCI probe order is not synchronous with this unit, so give the NICs a
# moment to all show up before giving in.
for _ in $(seq 30); do
  classify && break
  sleep 1
done

if ! classify; then
  echo "initialize-network: NIC inventory:" >&2
  inventory >&2
  fatal "expected 2 10GbE and at most 4 1GbE NICs, found ${#xe[@]} and ${#ge[@]}"
fi

# Ascending MAC order.  sysfs MACs are fixed-width lowercase hex, so a plain
# lexicographic sort is a numeric sort.
# Guarded: printf on an empty array still emits one blank line, which
# mapfile would turn into a phantom entry.
ge_order=(); xe_order=()
(( ${#ge[@]} )) && mapfile -t ge_order < <(printf '%s\n' "${ge[@]}" | sort)
(( ${#xe[@]} )) && mapfile -t xe_order < <(printf '%s\n' "${xe[@]}" | sort)

# names[i] is the final name for order[i].  1GbE fill eth0 upward; 10GbE are
# always eth4/eth5 so the bond config never depends on how many 1GbE exist.
order=()
names=()
for i in "${!ge_order[@]}"; do order+=("${ge_order[$i]}"); names+=("eth${i}"); done
for i in "${!xe_order[@]}"; do order+=("${xe_order[$i]}"); names+=("eth$((4 + i))"); done

# --- rename ---------------------------------------------------------------
#
# Two passes: every NIC goes to a scratch name first, because the target names
# are drawn from the same eth0..eth5 pool the kernel already handed out and a
# direct rename would collide.

for i in "${!order[@]}"; do
  dev="${order[$i]#* }"
  ip link set dev "$dev" down || fatal "cannot down ${dev}"
  ip addr flush dev "$dev"
  ip link set dev "$dev" name "nic${i}" || fatal "cannot rename ${dev} to nic${i}"
done

for i in "${!order[@]}"; do
  ip link set dev "nic${i}" name "${names[$i]}" || fatal "cannot rename nic${i} to ${names[$i]}"
done

# --- address --------------------------------------------------------------

[[ -r /etc/nodeinfo.env ]] || fatal "/etc/nodeinfo.env is missing"
. /etc/nodeinfo.env

write_addresses() {
  local bond="$1"; shift
  local dir="/etc/systemd/network/40-${bond}.network.d"
  mkdir -p "$dir"
  {
    echo "# Generated by initialize-network.sh from /etc/nodeinfo.env."
    echo "[Network]"
    printf 'Address=%s\n' "$@"
  } > "${dir}/10-address.conf"
}

write_addresses private "${PRIVATE_IP}/24"
write_addresses public  "${PUBLIC_IP}/27" "${PUBLIC_IP6}/64"
write_addresses cluster "${CLUSTER_IP}/24"
